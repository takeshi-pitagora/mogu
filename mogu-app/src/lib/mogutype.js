export const TYPE_DETAIL_URL = (code) => `https://mogutype.com/types/${String(code).toLowerCase()}`;

// 回答 { 'V-01': 0〜3, ... } → { code: 'VNBP', axes: { VT, NF, BG, PL } }
export function calculateDiagnosis(answers) {
  const axes = {};
  for (const axis of AXES) {
    const values = QUESTIONS.filter((x) => x.axis === axis.key)
      .map((x) => answers[x.id])
      .filter((v) => Number.isInteger(v));
    if (values.length === 0) return null;
    axes[axis.key] = Math.round((values.reduce((a, b) => a + b, 0) / values.length) * 100) / 100;
  }
  const code = AXES.map((axis) => (axes[axis.key] < 1.5 ? axis.left : axis.right)).join('');
  return { code, axes };
}

// プロフィールに保存されている food_style（タイプコード）から、タイプ情報を取り出す
export function getType(code) {
  const c = String(code || '').toUpperCase();
  return TYPES[c] ? { code: c, ...TYPES[c] } : null;
}
