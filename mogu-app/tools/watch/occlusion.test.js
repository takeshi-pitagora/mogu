const fs=require('fs'),path=require('path'),http=require('http'),puppeteer=require('puppeteer-core');
const DIST='/home/claude/work/watch/dist',PORT=54333;
const W=fs.readFileSync('/home/claude/work/watch/watchers.js','utf8');
const T={'.js':'text/javascript','.css':'text/css','.html':'text/html','.svg':'image/svg+xml','.png':'image/png','.woff2':'font/woff2','.json':'application/json','.map':'application/json'};
const sleep=m=>new Promise(r=>setTimeout(r,m));
(async()=>{
  const srv=http.createServer((q,s)=>{let f=path.join(DIST,decodeURIComponent(new URL(q.url,'http://x').pathname));
    if(!fs.existsSync(f)||fs.statSync(f).isDirectory())f=path.join(DIST,'index.html');
    s.writeHead(200,{'content-type':T[path.extname(f)]||'application/octet-stream'});fs.createReadStream(f).pipe(s);});
  await new Promise(r=>srv.listen(PORT,'127.0.0.1',r));
  const br=await puppeteer.launch({executablePath:'/usr/bin/google-chrome',headless:'new',args:['--no-sandbox','--disable-gpu']});
  const pg=await br.newPage();
  await pg.setViewport({width:393,height:852,deviceScaleFactor:2,isMobile:true,hasTouch:true});
  await pg.evaluateOnNewDocument(W);
  await pg.goto(`http://127.0.0.1:${PORT}/`,{waitUntil:'networkidle2'});await sleep(1500);
  const tap=w=>pg.evaluate(t=>{const n=x=>(x||'').replace(/\s+/g,'');
    const h=[...document.querySelectorAll('button,[role="button"],a[href]')].find(b=>n(b.textContent).includes(n(t))||n(b.getAttribute('aria-label')).includes(n(t)));
    if(!h)return false;h.click();return true;},w);
  const t1 = await tap('お店を登録');
  await sleep(2000);
  console.log('登録を開いた:', t1, '／入力欄の数:', await pg.evaluate(()=>document.querySelectorAll('input').length));
  console.log('シートの中:', (await pg.evaluate(()=>document.body.innerText)).replace(/\s+/g,' ').slice(0,220));
  await pg.evaluate(()=>{const e=document.querySelector('input');
    const s=Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype,'value').set;
    e.focus();s.call(e,'みゆき食堂');e.dispatchEvent(new Event('input',{bubbles:true}));});
  await sleep(1400);
  await tap('新しく登録する'); await sleep(1200);
  const found=await pg.evaluate(()=>window.__WATCH.checkContent('お店を登録する（駅）'));
  const hidden=found.filter(c=>c.kind==='隠れていて押せないボタン');
  console.log('隠れていて押せないボタン:', hidden.length ? hidden.map(c=>c.detail).join(' / ') : 'なし');
  await pg.screenshot({path:'/home/claude/work/watch/occl.png'});
  await br.close();srv.close();
})();
